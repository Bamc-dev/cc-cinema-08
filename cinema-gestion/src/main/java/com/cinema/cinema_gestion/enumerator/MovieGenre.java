/**
 * Genres cinématographiques d'un film.
 */
public enum MovieGenre {
    /** Film d'action. */
    ACTION,
    /** Film d'aventure. */
    ADVENTURE,
    /** Comédie. */
    COMEDY,
    /** Drame. */
    DRAMA,
    /** Film fantastique. */
    FANTASY,
    /** Film d'horreur. */
    HORROR,
    /** Film à énigme / mystère. */
    MYSTERY,
    /** Film romantique. */
    ROMANCE,
    /** Science-fiction. */
    SCIENCE_FICTION,

}
